import os
import io
import tempfile
from datetime import datetime
import streamlit as st
import torch
import torch.nn as nn
import numpy as np
from PIL import Image
from fpdf import FPDF
from torchvision import models, transforms
from pytorch_grad_cam import GradCAM
from pytorch_grad_cam.utils.image import show_cam_on_image

st.set_page_config(page_title="Brain MRI Diagnosis AI", page_icon="🧠", layout="wide")

CLASS_INFO = {
    "glioma": "Tumor originating in the glial cells of the brain or spine.",
    "meningioma": "Tumor arising from the meninges (membranes surrounding the brain and spinal cord).",
    "notumor": "No abnormal tumor mass detected in the MRI scan.",
    "pituitary": "Abnormal growth developing in the pituitary gland at the base of the brain.",
}

@st.cache_resource
def load_model():
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    checkpoint = torch.load("models/best_model.pth", map_location=device, weights_only=True)
    classes = checkpoint.get("class_names", ["glioma", "meningioma", "notumor", "pituitary"])
    img_size = checkpoint.get("image_size", 224)

    model = models.efficientnet_b0()
    model.classifier[1] = nn.Linear(model.classifier[1].in_features, len(classes))
    model.load_state_dict(checkpoint["model_state_dict"])
    model.to(device).eval()
    return model, device, classes, img_size

def generate_pdf_report(orig_img, cam_img, pred_class, confidence, classes, probs):
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(0, 12, "Brain MRI AI Diagnostic Summary", ln=True, align="C")

    pdf.set_font("Helvetica", "", 10)
    pdf.cell(0, 8, f"Generated on: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} | Model: EfficientNet-B0", ln=True, align="C")
    pdf.ln(6)

    # Save temporary images for FPDF embedding
    with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f1, \
         tempfile.NamedTemporaryFile(suffix=".png", delete=False) as f2:
        orig_img.save(f1.name)
        Image.fromarray(cam_img).save(f2.name)
        orig_path, cam_path = f1.name, f2.name

    pdf.image(orig_path, x=25, y=40, w=70)
    pdf.image(cam_path, x=115, y=40, w=70)
    os.remove(orig_path)
    os.remove(cam_path)

    pdf.set_y(115)
    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 10, f"Primary Prediction: {pred_class.upper()} ({confidence:.2f}% Confidence)", ln=True)

    pdf.set_font("Helvetica", "", 11)
    pdf.multi_cell(0, 7, f"Clinical Note: {CLASS_INFO.get(pred_class, '')}")
    pdf.ln(5)

    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "Class Probability Breakdown:", ln=True)
    pdf.set_font("Helvetica", "", 11)
    for cls, prob in zip(classes, probs):
        pdf.cell(0, 7, f"  - {cls.capitalize()}: {prob*100:.2f}%", ln=True)

    pdf.ln(10)
    pdf.set_font("Helvetica", "I", 9)
    pdf.multi_cell(0, 5, "Disclaimer: This report is generated by an AI research prototype and must not be used as a substitute for professional medical diagnosis.")

    return bytes(pdf.output())

model, device, CLASSES, IMG_SIZE = load_model()

transform = transforms.Compose([
    transforms.Resize((IMG_SIZE, IMG_SIZE)),
    transforms.ToTensor(),
    transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225]),
])

st.title("🧠 Brain Tumor MRI Classification & Explainability")
st.caption("Powered by EfficientNet-B0 (PyTorch + CUDA) & Grad-CAM")

with st.sidebar:
    st.header("Model Info")
    st.write("**Architecture:** EfficientNet-B0")
    st.write(f"**Inference Device:** `{device.type.upper()}`")
    st.warning("Disclaimer: For educational and research assistance only. Not a clinical medical diagnosis.")

tab1, tab2 = st.tabs(["🔬 Live MRI Diagnosis", "📊 Model Performance"])

with tab1:
    uploaded_file = st.file_uploader("Upload a Brain MRI Scan (JPG, JPEG, PNG)", type=["jpg", "jpeg", "png"])

    if uploaded_file is not None:
        image = Image.open(uploaded_file).convert("RGB")
        resized_img = image.resize((IMG_SIZE, IMG_SIZE))
        rgb_float = np.array(resized_img, dtype=np.float32) / 255.0
        input_tensor = transform(image).unsqueeze(0).to(device)

        with torch.no_grad():
            logits = model(input_tensor)
            probs = torch.softmax(logits, dim=1)[0].cpu().numpy()

        pred_idx = int(np.argmax(probs))
        pred_class = CLASSES[pred_idx]
        confidence = probs[pred_idx] * 100

        target_layers = [model.features[-1]]
        with GradCAM(model=model, target_layers=target_layers) as cam:
            grayscale_cam = cam(input_tensor=input_tensor, targets=None)[0]
        cam_overlay = show_cam_on_image(rgb_float, grayscale_cam, use_rgb=True)

        col1, col2, col3 = st.columns([1, 1, 1.2])
        with col1:
            st.subheader("Uploaded MRI")
            st.image(resized_img, use_container_width=True)
        with col2:
            st.subheader("Grad-CAM Focus")
            st.image(cam_overlay, use_container_width=True)
        with col3:
            st.subheader("Diagnosis Result")
            st.metric(label="Predicted Condition", value=pred_class.upper(), delta=f"{confidence:.2f}% Confidence")
            st.info(CLASS_INFO.get(pred_class, ""))
            st.write("**Class Probability Breakdown:**")
            for cls, prob in zip(CLASSES, probs):
                st.progress(float(prob), text=f"{cls.capitalize()}: {prob*100:.2f}%")

            pdf_bytes = generate_pdf_report(resized_img, cam_overlay, pred_class, confidence, CLASSES, probs)
            st.download_button(
                label="📄 Download PDF Report",
                data=pdf_bytes,
                file_name=f"MRI_Report_{pred_class}.pdf",
                mime="application/pdf",
            )

with tab2:
    st.subheader("Test Set Evaluation")
    if os.path.exists("models/confusion_matrix.png"):
        st.image("models/confusion_matrix.png", caption="Confusion Matrix on Unseen Test Set", width=550)